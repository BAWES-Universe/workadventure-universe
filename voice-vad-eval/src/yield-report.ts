// Turns yield-replay.jsonl into the comparison tables. Report half only (the replay is run on it).
//   tsx src/yield-report.ts <out dir>
// Speech clips should stop the bot; noise clips should not. "Stopped" is for good (the answer is lost); "paused" and
// "turned down" are the reversible yields. The person's recording starts 1.0 s into every speech clip (LEAD in
// fixtures.ts): a stop before that came from the background, not from them.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { LEAD } from './fixtures.ts';
import { percentile } from './scoring.ts';

interface Outcome {
    yieldAt?: number;
    stopAt?: number;
    pauses: number;
    heldMs: number;
    resumes: number;
    why: Record<string, number>;
}
interface Row {
    id: string;
    kind: 'noise' | 'speech' | 'burst';
    set: string;
    label: string;
    condition: string;
    provider: 'empty' | 'words';
    seconds: number;
    onsetMs?: number;
    result: Record<string, Outcome>;
}
const POLICIES = ['today', 'confirm', 'hold', 'dip'] as const;
const NAMES: Record<string, string> = { today: "today's rule", confirm: 'stop only when confirmed', hold: 'pause, then stop or go on', dip: 'turn down, then stop or back up' };

const [out] = process.argv.slice(2);
if (!out) throw new Error('usage: yield-report.ts <out dir>');
const rows = readFileSync(join(out, 'yield-replay.jsonl'), 'utf8')
    .split('\n')
    .filter(Boolean)
    .map((line) => JSON.parse(line) as Row);

const clipStartMs = LEAD * 1000;
const pct = (n: number, d: number) => (d ? `${((100 * n) / d).toFixed(1)}%` : '-');
const ms = (x: number) => (Number.isNaN(x) ? '-' : `${Math.round(x)} ms`);
const lines: string[] = [];
const say = (s = '') => lines.push(s);

say('# Interruption replay: today vs three candidates, same inputs');
say();
say('Generated by `src/yield-replay.ts` + `src/yield-report.ts`. Report half of the fixtures only. The worker\'s own Recognition and YieldControl code,');
say('simulated time, Silero probabilities from `results/raw.jsonl.gz`. The speech-to-text provider is SCRIPTED (see yield-replay.ts):');
say('these numbers test the logic, not a real provider\'s timing. The bot is taken to be speaking throughout every clip.');
say();

// ---- Speech: should stop ----
const speech = rows.filter((r) => r.kind === 'speech');
say(`## People speaking over the bot (${speech.length} clips): should stop`);
say();
say('| behaviour | stopped for the person | never stopped | stopped by background first | first change after onset, median / p95 | stopped for good after onset, median / p95 |');
say('| --- | --- | --- | --- | --- | --- |');
for (const policy of POLICIES) {
    let forPerson = 0;
    let never = 0;
    let background = 0;
    const yields: number[] = [];
    const stops: number[] = [];
    for (const r of speech) {
        const o = r.result[policy];
        if (o.stopAt === undefined) never++;
        else if (o.stopAt < clipStartMs) background++;
        else {
            forPerson++;
            stops.push(o.stopAt - r.onsetMs!);
        }
        if (o.yieldAt !== undefined && o.yieldAt >= clipStartMs) yields.push(o.yieldAt - r.onsetMs!);
    }
    say(`| ${NAMES[policy]} | ${forPerson} (${pct(forPerson, speech.length)}) | ${never} (${pct(never, speech.length)}) | ${background} | ${ms(percentile(yields, 0.5))} / ${ms(percentile(yields, 0.95))} | ${ms(percentile(stops, 0.5))} / ${ms(percentile(stops, 0.95))} |`);
}
say();
say('Never stopped, by set and condition:');
say();
say('| set | condition | clips | ' + POLICIES.map((p) => NAMES[p]).join(' | ') + ' |');
say('| --- | --- | --- | ' + POLICIES.map(() => '---').join(' | ') + ' |');
const groups = new Map<string, Row[]>();
for (const r of speech) groups.set(`${r.set}|${r.condition}`, [...(groups.get(`${r.set}|${r.condition}`) ?? []), r]);
for (const [key, group] of [...groups].sort()) {
    const [set, condition] = key.split('|');
    say(`| ${set} | ${condition} | ${group.length} | ` + POLICIES.map((p) => String(group.filter((r) => r.result[p].stopAt === undefined).length)).join(' | ') + ' |');
}
say();

// ---- Noise: should not stop ----
for (const provider of ['empty', 'words'] as const) {
    const noise = rows.filter((r) => r.kind !== 'speech' && r.provider === provider);
    const minutes = noise.reduce((a, r) => a + r.seconds, 0) / 60;
    say(`## Noise and knocks (${noise.length} clips, ${minutes.toFixed(0)} min), provider ${provider === 'empty' ? 'hears nothing (a successful empty result)' : 'hears words in anything (background speech transcribed)'}: should not stop`);
    say();
    say('| behaviour | group | clips stopped for good | pauses or dips per minute | held seconds per minute | went on again |');
    say('| --- | --- | --- | --- | --- | --- |');
    const byGroup = new Map<string, Row[]>();
    for (const r of noise) {
        const group = r.kind === 'burst' ? 'three knocks' : r.label;
        byGroup.set(group, [...(byGroup.get(group) ?? []), r]);
    }
    for (const policy of POLICIES) {
        for (const [group, members] of [...byGroup].sort()) {
            const mins = members.reduce((a, r) => a + r.seconds, 0) / 60;
            const stopped = members.filter((r) => r.result[policy].stopAt !== undefined).length;
            const pauses = members.reduce((a, r) => a + r.result[policy].pauses, 0);
            const held = members.reduce((a, r) => a + r.result[policy].heldMs, 0) / 1000;
            const resumes = members.reduce((a, r) => a + r.result[policy].resumes, 0);
            say(`| ${NAMES[policy]} | ${group} (${members.length}) | ${stopped} (${pct(stopped, members.length)}) | ${(pauses / mins).toFixed(2)} | ${(held / mins).toFixed(1)} | ${resumes} |`);
        }
    }
    say();
    say('What ended the stops, and how long the bot could talk before its first stop (median over clips that stopped):');
    say();
    say('| behaviour | noise level (dBFS) | clips | stopped | first stop after, median | detector heard speech | words / failed | waited too long (6 s) |');
    say('| --- | --- | --- | --- | --- | --- | --- | --- |');
    for (const policy of POLICIES) {
        const levels = new Map<string, Row[]>();
        for (const r of noise.filter((x) => x.kind === 'noise')) levels.set(r.condition, [...(levels.get(r.condition) ?? []), r]);
        for (const [level, members] of [...levels].sort((a, b) => Number(a[0]) - Number(b[0]))) {
            const stopped = members.filter((r) => r.result[policy].stopAt !== undefined);
            const sum = (key: RegExp) => members.reduce((a, r) => a + Object.entries(r.result[policy].why ?? {}).filter(([k]) => key.test(k)).reduce((b, [, v]) => b + v, 0), 0);
            const first = percentile(
                stopped.map((r) => r.result[policy].stopAt! / 1000),
                0.5
            );
            say(
                `| ${NAMES[policy]} | ${level} | ${members.length} | ${stopped.length} | ${Number.isNaN(first) ? '-' : first.toFixed(1) + ' s'} | ${policy === 'today' ? '-' : sum(/^confirmed_(detector|fallback)$/)} | ${policy === 'today' ? '-' : sum(/^confirmed_(words|stt_failed|command)$/)} | ${policy === 'today' ? '-' : sum(/^watchdog$/)} |`
            );
        }
    }
    say();
}
writeFileSync(join(out, 'yield-replay.md'), lines.join('\n') + '\n');
console.log(lines.join('\n'));
