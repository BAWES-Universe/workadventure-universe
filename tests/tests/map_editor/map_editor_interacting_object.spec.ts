import {expect, test} from "@playwright/test";
import Map from "../utils/map";
import AreaEditor from "../utils/map-editor/areaEditor";
import EntityEditor from "../utils/map-editor/entityEditor";
import {resetWamMaps} from "../utils/map-editor/uploader";
import MapEditor from "../utils/mapeditor";
import Menu from "../utils/menu";
import {map_storage_url} from "../utils/urls";
import {getPage} from "../utils/auth";
import {isMobile} from "../utils/isMobile";

test.setTimeout(240_000); // Fix Webkit that can take more than 60s
test.use({
  baseURL: map_storage_url,
});

test.describe("Map editor interacting with object @oidc @nomobile", () => {
  test.beforeEach(
    "Ignore tests on mobilechromium because map editor not available for mobile devices",
      ({ page }) => {
      // Map Editor not available on mobile
      test.skip(isMobile(page), 'Map editor is not available on mobile');
    }
  );

  // https://github.com/element-hq/synapse/issues/19303 - skip webkit due to synapse v1.144.0 OIDC issues 
  test("Success to interact with area @nowebkit", async ({ browser, request }) => {
    // Go to the map
    await resetWamMaps(request);
    await using page = await getPage(browser, 'Admin1', Map.url("empty"));

    // Create area on the map for the test
    await Menu.openMapEditor(page);
    await MapEditor.openAreaEditor(page);
    await AreaEditor.drawArea(
      page,
      { x: 8 * 32 * 1.5, y: 8 * 32 * 1.5 },
      { x: 10 * 32 * 1.5, y: 10 * 32 * 1.5 }
    );
    await AreaEditor.setAreaName(page, "MyLinkZone");
    await AreaEditor.addProperty(page, "openWebsite");
    await AreaEditor.setOpenLinkProperty(
      page,
      "https://workadventu.re",
      "Show action toast with message"
    );
    await Menu.closeMapEditor(page);

    // Walk to the area
    await Map.teleportToPosition(page, 9 * 32, 9 * 32);

    // Test if the DomElement generated by the character is visible
    await expect(page.getByText('Press Space to open the website')).toBeVisible();

    await page.context().close();
  });

  test("Success to interact with entity @nowebkit", async ({ browser, request, browserName }) => {
    // Skip the test on Webkit because the click up doesn't work
    test.skip(browserName === 'webkit', 'WebKit click up does not work here');

    // Go to the map
    await resetWamMaps(request);
    await using page = await getPage(browser, 'Admin1', Map.url("empty"));

    // Create entity on the map for the test
    await Menu.openMapEditor(page);
    await MapEditor.openEntityEditor(page);
    await EntityEditor.selectEntity(page, 0, "small table");
    await EntityEditor.moveAndClick(page, 1, 8.5 * 32 * 1.5);
    await EntityEditor.clearEntitySelection(page);
    // await EntityEditor.moveAndClick(page, 1, 8.5 * 32 * 1.5);
    await EntityEditor.moveAndClick(page, 1, 8.5 * 32 * 1.45);
    await EntityEditor.setEntityName(page, "My Open Link");
    await EntityEditor.addProperty(page, "openWebsite");
    await EntityEditor.setOpenLinkProperty(page, "https://workadventu.re");
    await Menu.closeMapEditor(page);

    // Refresh the page to see the entity
    await page.goto(Map.url("empty"));
    // Wait for the map to be loaded
    await Menu.waitForMapLoad(page);
    //await expect(page.locator("button#menuIcon").nth(0)).toBeVisible();

    // Move to the entity
    await EntityEditor.moveAndRightClick(page, 0, 8.5 * 32 * 1.5);

    // Test if the DomElement generated by the character is visible
    await expect(page.locator("span.characterTriggerAction")).toBeVisible();

    await page.context().close();
  });

  test("Success to interact with openFile area and entity @nowebkit", async ({ browser, request, browserName }) => {
    // Skip the test on Webkit because the click up doesn't work
    test.skip(browserName === 'webkit', 'WebKit click up does not work here');

    // Go to the map
    await resetWamMaps(request);
    await using page = await getPage(browser, 'Admin1', Map.url("empty"));

    // Create entity on the map for the test
    await Menu.openMapEditor(page);
    await MapEditor.openEntityEditor(page);
    await EntityEditor.selectEntity(page, 0, "small table");
    await EntityEditor.moveAndClick(page, 1, 8.5 * 32 * 1.5);
    await EntityEditor.clearEntitySelection(page);
    // await EntityEditor.moveAndClick(page, 1, 8.5 * 32 * 1.5);
    await EntityEditor.moveAndClick(page, 1, 8.5 * 32 * 1.45);
    await EntityEditor.setEntityName(page, "My Open Link");
    await EntityEditor.addProperty(page, "openFile");
    await EntityEditor.setOpenFileProperty(page);
    await Menu.closeMapEditor(page);

    // // Refresh the page to see the entity
    // await page.goto(Map.url("empty"));
    // // Wait for the map to be loaded
    // await Menu.waitForMapLoad(page);

    // Move to the entity
    await EntityEditor.moveAndRightClick(page, 0, 8.5 * 32 * 1.5);

    // A PDF opens in the file viewer beside the map, which reads the file from the map storage with the player's pass.
    const entityFileResponse = page.waitForResponse((response) => response.url().includes("ipsum-lorem"));
    await page.keyboard.press("Space");
    await expect(page.getByRole("dialog", { name: /ipsum-lorem/ })).toBeVisible();
    const fileUrlE = (await entityFileResponse).url();

    // Refresh the page to create area
    await page.goto(Map.url("empty"));
    // Wait for the map to be loaded
    await Menu.waitForMapLoad(page);

    // Create area on the map for the test
    await Menu.openMapEditor(page);
    await MapEditor.openAreaEditor(page);
    await AreaEditor.drawArea(
      page,
      { x: 8 * 32 * 1.5, y: 8 * 32 * 1.5 },
      { x: 10 * 32 * 1.5, y: 10 * 32 * 1.5 }
    );
    await AreaEditor.setAreaName(page, "MyLinkZone");
    await AreaEditor.addProperty(page, "openFile");
    await AreaEditor.setOpenFileProperty(
      page,
      "Show immediately on enter"
    );

    // Walk to the area
    const areaFileResponse = page.waitForResponse((response) => response.url().includes("lorem-ipsum"));
    await Map.teleportToPosition(page, 9 * 32, 9 * 32);

    // The area's PDF opens in the file viewer too
    await expect(page.getByRole("dialog", { name: /lorem-ipsum/ })).toBeVisible();
    const fileUrlA = (await areaFileResponse).url();

    // Check if the PDF file of the entity is accessible
    const uploadFileE1 = request.post(fileUrlE);
    expect((await uploadFileE1).ok()).toBeTruthy();

    // Check if the PDF file of the area is accessible
    const uploadFileA1 = request.post(fileUrlA);
    expect((await uploadFileA1).ok()).toBeTruthy();

    await AreaEditor.deleteFile(page);

    // Check if the PDF file of the area is still accessible
    const uploadedFileA2 = request.post(fileUrlA);
    expect((await uploadedFileA2).ok()).toBeFalsy();

    await Menu.closeMapEditor(page);

    // Now let's check Entity PDF file deletion, from a fresh page: the area's file viewer is closed and the small map
    // is back in the middle of the screen, so the entity is where it was placed.
    await page.goto(Map.url("empty"));
    await Menu.waitForMapLoad(page);
    await page.keyboard.press("e");
    await EntityEditor.moveAndClick(page, 1, 8.5 * 32 * 1.45);
    await page.keyboard.press("Delete");

    // The deletion travels through the pusher and the back to map-storage; the file is gone a moment later.
    await expect.poll(async () => (await request.post(fileUrlE)).ok()).toBeFalsy();


    await page.context().close();
  });
});
